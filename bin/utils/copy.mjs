/** Write _config/manifest.yaml recording installed version and modules. */
export function writeManifest(targetDir, version, modules) {
  const content = `# AI-QA-Framework Install Manifest
# Do not edit manually.
version: "${version}"
installed_at: "${new Date().toISOString()}"
modules:
${modules.map(m => `  - ${m}`).join('\n')}
`;
  mkdirSync(join(targetDir, '_config'), { recursive: true });
  writeFileSync(join(targetDir, '_config', 'manifest.yaml'), content);
}

/** Write AI tool integration stubs into the host project (cwd). */
export function writeToolStubs(tools, installDir) {
  for (const tool of tools) {
    switch (tool) {
      case 'claude-code': {
        const dir = join(process.cwd(), '.claude', 'commands');
        mkdirSync(dir, { recursive: true });
        writeFileSync(join(dir, 'qa.md'), `# QA — AI QA Framework
Run the Rayan QA agent. Load \`${installDir}/agents/qae.md\` to activate.
`);
        break;
      }
      case 'cursor': {
        const path = join(process.cwd(), '.cursorrules');
        const stub = `# AI QA Framework\nQA agent: ./${installDir}/agents/qae.md\nConfig: ./${installDir}/config.yaml\n`;
        if (!existsSync(path)) writeFileSync(path, stub);
        break;
      }
      case 'copilot': {
        const dir = join(process.cwd(), '.github');
        mkdirSync(dir, { recursive: true });
        writeFileSync(join(dir, 'copilot-instructions.md'), `# AI QA Framework\nQA agent persona: ./${installDir}/agents/qae.md\nConfig: ./${installDir}/config.yaml\n`);
        break;
      }
    }
  }
}
