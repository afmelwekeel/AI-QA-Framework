import { cpSync, mkdirSync, existsSync, writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Resolve the root directory of the ai-qa-framework package itself. */
export function packageRoot() {
  return join(fileURLToPath(import.meta.url), '..', '..', '..');
}

/** The directories/files that make up the framework (what gets copied on install). */
const FRAMEWORK_DIRS = [
  'agents',
  'adapters',
  'commands',
  'core',
  'project-detectors',
  'reusable-prompts',
  'rules',
  'skills',
  'templates',
  'workflows',
  '_config',
  '_memory',
];

const FRAMEWORK_FILES = [
  'playwright.config.js',
];

/** Module → skill folders it includes */
const MODULE_SKILLS = {
  'core':               null, // always — copies everything above
  'e2e-playwright':     ['playwright-generation', 'test-execution'],
  'test-cases-xlsx':    ['test-case-generation'],
  'security-scan':      ['security-validation'],
  'accessibility-scan': ['accessibility-validation'],
  'regression-testing': ['regression-testing'],
};

/**
 * Copy the framework into targetDir.
 * selectedModules: array of module id strings. 'core' is always implied.
 */
export function copyFramework(targetDir, selectedModules = ['core']) {
  const src = packageRoot();
  mkdirSync(targetDir, { recursive: true });

  // Always copy structural dirs/files
  for (const dir of FRAMEWORK_DIRS) {
    const srcPath = join(src, dir);
    const dstPath = join(targetDir, dir);
    if (existsSync(srcPath)) {
      cpSync(srcPath, dstPath, { recursive: true, force: true });
    }
  }
  for (const file of FRAMEWORK_FILES) {
    const srcPath = join(src, file);
    const dstPath = join(targetDir, file);
    if (existsSync(srcPath)) {
      cpSync(srcPath, dstPath, { force: true });
    }
  }

  // Create empty TestResult placeholder
  const trDir = join(targetDir, 'TestResult');
  mkdirSync(trDir, { recursive: true });
  writeFileSync(join(trDir, '.gitkeep'), '');

  // Create package.json inside installed dir for npm install
  writeInstalledPackageJson(targetDir, src);
}

/** Write a minimal package.json in the installed framework dir for `npm install`. */
function writeInstalledPackageJson(targetDir, src) {
  const srcPkg = JSON.parse(readFileSync(join(src, 'package.json'), 'utf8'));
  const localPkg = {
    name: `${srcPkg.name}-local`,
    version: srcPkg.version,
    private: true,
    type: 'module',
    description: `AI-QA-Framework installed in this project`,
    scripts: {
      qa:            'node ./core/orchestrator.mjs',
      detect:        'node ./core/orchestrator.mjs detect',
      'analyze-story': 'node ./core/orchestrator.mjs analyze-story',
      'test-cases':  'node ./core/orchestrator.mjs generate-test-cases',
      e2e:           'node ./core/orchestrator.mjs generate-e2e',
      'test-data':   'node ./core/orchestrator.mjs generate-test-data',
      'run-tests':   'playwright test --headed',
      'run-tests:ci':'playwright test',
      bugs:          'node ./core/orchestrator.mjs analyze-bugs',
      report:        'node ./core/orchestrator.mjs generate-report',
      full:          'node ./core/orchestrator.mjs full-workflow',
    },
    dependencies: srcPkg.dependencies || {},
    devDependencies: srcPkg.devDependencies || {},
  };
  writeFileSync(join(targetDir, 'package.json'), JSON.stringify(localPkg, null, 2) + '\n');
}

/** Write config.yaml with user's answers into targetDir. */
