import { existsSync, readFileSync, writeFileSync, renameSync, cpSync, rmSync, readdirSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT_DIR, CORE_DIR, RESULT_DIR, INSTALL_DIR } from './copy.mjs';

/** Old command names replaced in v3.3.0. */
const OLD_COMMANDS = ['aiqa-writetestcases', 'aiqa-executetests'];

/** Integration-file folders and the suffix each tool uses. */
const COMMAND_LOCATIONS = [
  { dir: ['.claude', 'commands'], ext: '.md' },
  { dir: ['.github', 'prompts'],  ext: '.prompt.md' },
  { dir: ['.cursor', 'rules'],    ext: '.mdc' },
  { dir: ['.windsurf', 'rules'],  ext: '.md' },
];

/** Stub files that mention the install dir by path. */
const STUB_FILES = [
  ['.claude', 'commands', 'qa.md'],
  ['.cursorrules'],
  ['.github', 'copilot-instructions.md'],
];

const escapeRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Migrate a legacy install to <root>/AI-QA-Framework/{Core,TestResult}.
 * Handles: flat v3.0–3.2 installs (any folder, e.g. ai-qa-framework/, results inside it)
 * and v3.3.0 installs (./Core + ./TestResult at the project root).
 * Windows/macOS are case-insensitive, so the legacy folder is moved via a temp name first
 * (ai-qa-framework/ and AI-QA-Framework/ are the same path there).
 * Returns { migrated, steps[], warning? }.
 */
export function migrateLegacyInstall(legacyDir, root = process.cwd()) {
  const steps = [];
  if (legacyDir === INSTALL_DIR) return { migrated: false, steps };

  const legacyPath = join(root, legacyDir);
  const wrapper    = join(root, ROOT_DIR);
  const corePath   = join(wrapper, CORE_DIR);
  const resultPath = join(wrapper, RESULT_DIR);
  const rootResults = join(root, RESULT_DIR);       // v3.3.0 location
  const tmpPath    = join(root, `.aiqa-migrate-${Date.now()}`);

  // 1. Legacy folder → temp name first (frees the name on case-insensitive filesystems,
  //    where ai-qa-framework/ and AI-QA-Framework/ are the same path), then → AI-QA-Framework/Core
  renameSync(legacyPath, tmpPath);
  try {
    if (existsSync(corePath)) {
      renameSync(tmpPath, legacyPath);
      return { migrated: false, steps, warning: `./${INSTALL_DIR}/ already exists — migration skipped. Merge ./${legacyDir}/ into it manually.` };
    }
    mkdirSync(wrapper, { recursive: true });
    renameSync(tmpPath, corePath);
  } catch (e) {
    // Roll back so the user is not left with a hidden temp folder
    if (!existsSync(legacyPath) && existsSync(tmpPath)) renameSync(tmpPath, legacyPath);
    throw e;
  }
  steps.push(`Moved ./${legacyDir}/ → ./${INSTALL_DIR}/`);

  // 2. Merge results (never overwrite) from inside Core (v3.0–3.2) and from ./TestResult (v3.3.0)
  const sources = [join(corePath, RESULT_DIR)];
  if (legacyDir === CORE_DIR) sources.push(rootResults);
  for (const src of sources) {
    if (!existsSync(src)) continue;
    mkdirSync(resultPath, { recursive: true });
    cpSync(src, resultPath, { recursive: true, force: false, errorOnExist: false });
    rmSync(src, { recursive: true, force: true });
    steps.push(`Moved ${src.slice(root.length + 1).replace(/\\/g, '/')}/ → ./${ROOT_DIR}/${RESULT_DIR}/`);
  }

  // 3. Point config.yaml output_folder at the new location
  const cfgPath = join(corePath, 'config.yaml');
  if (existsSync(cfgPath)) {
    const cfg = readFileSync(cfgPath, 'utf8');
    const next = cfg.replace(/^output_folder:.*$/m, `output_folder: "{project-root}/${ROOT_DIR}/${RESULT_DIR}"`);
    if (next !== cfg) {
      writeFileSync(cfgPath, next, 'utf8');
      steps.push(`Updated output_folder in ${INSTALL_DIR}/config.yaml`);
    }
  }

  // 4. Remove stale command files (old names + files pointing at the old folder)
  let removed = 0;
  for (const { dir, ext } of COMMAND_LOCATIONS) {
    const d = join(root, ...dir);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d)) {
      if (f.startsWith('aiqa-') || OLD_COMMANDS.some(o => f === o + ext)) {
        rmSync(join(d, f), { force: true });
        removed++;
      }
    }
  }
  const agentFile = join(root, '.github', 'agents', 'ai-qa-framework-qae.agent.md');
  if (existsSync(agentFile)) { rmSync(agentFile, { force: true }); removed++; }
  if (removed) steps.push(`Removed ${removed} stale command file(s) (regenerated by the command refresh)`);

  // 5. Fix path references in tool stubs
  const oldRef = new RegExp(`(?<![\\w/.-])${escapeRe(legacyDir)}/`, 'g');
  for (const parts of STUB_FILES) {
    const p = join(root, ...parts);
    if (!existsSync(p)) continue;
    const txt = readFileSync(p, 'utf8');
    const next = txt.replace(oldRef, `${INSTALL_DIR}/`);
    if (next !== txt) {
      writeFileSync(p, next, 'utf8');
      steps.push(`Updated paths in ${parts.join('/')}`);
    }
  }

  return { migrated: true, steps };
}
